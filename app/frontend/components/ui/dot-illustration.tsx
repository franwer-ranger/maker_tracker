export type Figure = keyof typeof figures

// 96×96 como en Paper: paso 6.4, radio 2.18.
export function DotIllustration({ figure, size = 96, className }: { figure: Figure; size?: number; className?: string }) {
  return (
    <svg aria-hidden="true" width={size} height={size} viewBox="0 0 96 96" className={cx("shrink-0", className)}>
      {figures[figure].flatMap((row, y) =>
        [...row].map((cell, x) => (
          <circle key={`${x}-${y}`} cx={3.2 + x * 6.4} cy={3.2 + y * 6.4} r={2.18} fill={cell === "#" ? "var(--body)" : "var(--border)"} />
        )),
      )}
    </svg>
  )
}
